#!/usr/bin/env python3
"""Transform the upstream BEQ database into a compact, versioned static catalogue.

The source database is intentionally parsed only in CI. The Remote downloads the
small browse index and individual filter payloads on demand.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from collections import defaultdict
from pathlib import Path
from typing import Any

SCHEMA_VERSION = 1
FILTER_FIELDS = ("type", "freq", "gain", "q")


def _canonical(value: Any) -> bytes:
    return json.dumps(value, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _compact_record(record: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    title = record.get("title")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("record has no valid title")

    raw_filters = record.get("filters")
    if not isinstance(raw_filters, list) or not raw_filters:
        raise ValueError(f"record {title!r} has no filters")

    filters: list[dict[str, Any]] = []
    for raw_filter in raw_filters:
        if not isinstance(raw_filter, dict):
            raise ValueError(f"record {title!r} contains a non-object filter")
        item = {field: raw_filter[field] for field in FILTER_FIELDS if field in raw_filter}
        if not all(field in item for field in FILTER_FIELDS):
            raise ValueError(f"record {title!r} contains an incomplete filter")
        filters.append(item)

    underlying = record.get("underlying") or title
    compact_payload = {
        "title": title,
        "underlying": underlying,
        "filters": filters,
    }
    # Preserve the media IDs generated by the previous integration implementation.
    entry_id = hashlib.md5(_canonical(compact_payload)).hexdigest()[:16]

    audio_types = record.get("audioTypes") or []
    if not isinstance(audio_types, list):
        raise ValueError(f"record {title!r} has invalid audioTypes")
    content_type = record.get("content_type") or "other"
    if not isinstance(content_type, str):
        raise ValueError(f"record {title!r} has invalid content_type")

    index_item = {
        "id": entry_id,
        "title": title,
        "author": str(record.get("author") or ""),
        "year": str(record.get("year") or ""),
        "audioTypes": [str(value) for value in audio_types],
        "content_type": content_type,
        "search_title": title.casefold(),
    }
    return index_item, compact_payload


def build(source: Path, output: Path) -> dict[str, Any]:
    raw = source.read_bytes()
    records = json.loads(raw)
    if not isinstance(records, list) or not records:
        raise ValueError("source catalogue must be a non-empty JSON array")

    source_digest = hashlib.sha256(raw).hexdigest()
    version = source_digest[:16]
    entries_dir = output / version / "entries"
    entries_dir.mkdir(parents=True, exist_ok=True)

    index_entries: list[dict[str, Any]] = []
    categories: dict[str, list[str]] = defaultdict(list)
    seen_ids: set[str] = set()
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("source catalogue contains a non-object record")
        item, payload = _compact_record(record)
        if item["id"] in seen_ids:
            raise ValueError(f"duplicate BEQ entry id: {item['id']}")
        seen_ids.add(item["id"])
        index_entries.append(item)
        categories[item["content_type"]].append(item["id"])
        (entries_dir / f"{item['id']}.json").write_bytes(_canonical(payload))

    index_entries.sort(key=lambda item: (item["title"].casefold(), item["id"]))
    index = {
        "schema_version": SCHEMA_VERSION,
        "version": version,
        "entries": index_entries,
        "categories": {key: sorted(ids, key=lambda entry_id: next(
            item["title"].casefold() for item in index_entries if item["id"] == entry_id
        )) for key, ids in sorted(categories.items())},
    }
    index_bytes = _canonical(index)
    (output / version / "index.json").write_bytes(index_bytes)
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "version": version,
        "source_sha256": source_digest,
        "entry_count": len(index_entries),
        "index": f"{version}/index.json",
        "index_sha256": hashlib.sha256(index_bytes).hexdigest(),
    }
    (output / "manifest.json").write_bytes(_canonical(manifest))
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        shutil.rmtree(args.output)
    args.output.mkdir(parents=True)
    manifest = build(args.source, args.output)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
